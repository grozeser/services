def section(i: int, s) -> str:
    cover, title, about, benefit, works = s
    cells = [f'<td width="33%" valign="top"><a href="portfolio/{f}.png"><img src="portfolio/{f}.png" alt="{n}"></a><br><b>{n}</b><br>{d}<br>{l}</td>'
             for f, n, d, l in works]
    grid = "<table>\n<tr>" + "".join(cells[:3]) + "</tr>\n<tr>" + "".join(cells[3:]) + "</tr>\n</table>"
    return f"""## {i}. {title}

<img src="covers/{cover}.png" width="420" alt="{title}">

{about}

**Зачем бизнесу:** {benefit}

{grid}

<p align="right"><a href="#услуги">↑ к списку услуг</a></p>
"""


